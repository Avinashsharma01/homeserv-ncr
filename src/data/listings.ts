/** Get listings filtered by region and/or locality and/or category */
export function getListings(filters: {
  region?: string;
  locality?: string;
  category?: string;
}): Listing[] {
  return listings.filter((l) => {
    if (filters.region && l.region !== filters.region) return false;
    if (filters.locality && l.locality !== filters.locality) return false;
    if (filters.category && l.category !== filters.category) return false;
    return true;
  });
}

/** Get a single listing by its ID */
export function getListingById(id: string): Listing | undefined {
  return listings.find((l) => l.id === id);
}

/** Get a single listing by its slug */
export function getListingBySlug(slug: string): Listing | undefined {
  return listings.find((l) => l.slug === slug);
}
